"""Validate the fictional host and real-person character cast for an Ourbites episode.

This validates documentation and declared planned scene usage only; it does not
certify that a rendered scene shows the correct asset, likeness, rights or pose.
Use --release before final human review; no approval is generated by this tool.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path
import re

REPO_ROOT = Path(__file__).resolve().parents[1]


class CharacterReviewError(ValueError):
    pass


def _load_profile(root: Path, slug: str, path: str) -> dict:
    if not re.fullmatch(r'[a-z][a-z0-9-]{0,79}', slug):
        raise CharacterReviewError('Invalid character id: ' + str(slug))
    expected = 'characters/' + ('protagonist' if slug == 'ourbites-protagonist' else slug) + '/profile.json'
    if path != expected:
        raise CharacterReviewError(slug + ': profile path must be ' + expected)
    location = root / expected
    try:
        data = json.loads(location.read_text(encoding='utf-8'))
    except (OSError, ValueError) as exc:
        raise CharacterReviewError(slug + ': missing or malformed profile') from exc
    if data.get('id') != slug:
        raise CharacterReviewError(slug + ': profile ID mismatch')
    return data


def _scene_ids(values: object, scene_ids: set[str], field: str) -> list[str]:
    if not isinstance(values, list) or not values:
        raise CharacterReviewError(field + ' must be a nonempty list')
    if len(set(values)) != len(values) or not set(values).issubset(scene_ids):
        raise CharacterReviewError(field + ' includes duplicate or unknown scenes')
    return values


def validate_character_cast(episode: dict, root: Path, release: bool = False) -> list[str]:
    if episode.get('language') != 'en':
        # Deliberately only channel-specific, not a universal media-engine rule.
        pass
    scenes = {s.get('id') for s in episode.get('scenes', []) if isinstance(s, dict)}
    if not scenes or not all(isinstance(i, str) for i in scenes):
        raise CharacterReviewError('Episode scenes are invalid')
    cast = episode.get('character_cast')
    if not isinstance(cast, dict):
        raise CharacterReviewError('Missing required Ourbites character_cast')
    host = cast.get('protagonist')
    if not isinstance(host, dict) or host.get('id') != 'ourbites-protagonist':
        raise CharacterReviewError('Ourbites requires the one canonical recurring protagonist')
    profile = _load_profile(root, host['id'], host.get('profile'))
    if (profile.get('type') != 'recurring_fictional_protagonist' or
            not profile.get('must_appear_in_every_video')):
        raise CharacterReviewError('Host profile is not the canonical fictional guide')
    _scene_ids(host.get('appearance_scene_ids'), scenes, 'protagonist appearance_scene_ids')
    warnings: list[str] = []
    if not profile.get('review', {}).get('approved'):
        if release:
            raise CharacterReviewError('The protagonist design is not human-approved; final release blocked')
        warnings.append('Protagonist is provisional: human appearance approval still required')
    if host.get('status') != profile.get('status'):
        raise CharacterReviewError('Host manifest/profile status mismatch')

    people = cast.get('real_people', [])
    if not isinstance(people, list):
        raise CharacterReviewError('real_people must be a list')
    seen = set()
    for person in people:
        if not isinstance(person, dict) or not isinstance(person.get('id'), str):
            raise CharacterReviewError('Invalid real-person cast entry')
        slug = person['id']
        if slug in seen or slug == host['id']:
            raise CharacterReviewError('Duplicate or illegal real-person cast ID: ' + slug)
        seen.add(slug)
        subject = _load_profile(root, slug, person.get('profile'))
        if subject.get('type') != 'stylized_real_person':
            raise CharacterReviewError(slug + ' must be a real-person character profile')
        if person.get('status') != subject.get('status'):
            raise CharacterReviewError(slug + ' manifest/profile status mismatch')
        for key in ('planned_scene_ids', 'appearance_scene_ids'):
            ids = person.get(key, [])
            if not isinstance(ids, list) or len(set(ids)) != len(ids) or not set(ids).issubset(scenes):
                raise CharacterReviewError(slug + ': invalid ' + key)
        if person.get('appearance_scene_ids') and not subject.get('review', {}).get('approved'):
            raise CharacterReviewError(slug + ': unapproved real-person likeness selected for a rendered scene')
        if subject.get('review', {}).get('approved'):
            review = subject['review']
            if not review.get('reviewer') or not review.get('asset_sha256'):
                raise CharacterReviewError(slug + ': claimed approval without named reviewer and exact asset hash')
        else:
            warnings.append(slug + ' remains concept-only; do not insert into final video')

    if release:
        reviewer = profile.get('review', {})
        if not reviewer.get('reviewer') or not reviewer.get('asset_sha256'):
            raise CharacterReviewError('Host approval requires reviewer and exact approved asset version')
    return warnings


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('episode', type=Path)
    parser.add_argument('--release', action='store_true',
                        help='reject provisional host and unapproved character assets')
    args = parser.parse_args()
    try:
        data = json.loads(args.episode.read_text(encoding='utf-8-sig'))
        warnings = validate_character_cast(data, REPO_ROOT, args.release)
        for note in warnings:
            print('REVIEW:', note)
        print('OK: character cast is structurally valid; render and editorial approval remain separate')
    except (CharacterReviewError, OSError, ValueError, KeyError, TypeError) as exc:
        parser.exit(1, 'STOP: ' + str(exc) + '\n')


if __name__ == '__main__':
    main()
